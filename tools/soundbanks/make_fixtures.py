"""Generate synthetic fixtures; SF3 wraps the attributed MIT FluidR3 excerpt."""
import math, pathlib, struct as s, zipfile
root=pathlib.Path(__file__).resolve().parents[2]/'tracker/tests/fixtures/soundbanks'
root.mkdir(exist_ok=True,parents=True)
def chunk(tag,payload,big=False):return tag+s.pack('>I' if big else '<I',len(payload))+payload+(b'\0' if len(payload)%2 else b'')
def name(n,w):return n.encode().ljust(w,b'\0')
frames=256
pcm=[int(22000*math.sin(n*2*math.pi/32)) for n in range(frames)]
smpl=s.pack('<9I',0,0,0,60,0,0,0,1,0)+s.pack('<6I',0,0,32,223,0,0)
wave=b'WAVE'+chunk(b'fmt ',s.pack('<HHIIHH',1,1,48000,96000,2,16))+chunk(b'smpl',smpl)+chunk(b'data',s.pack('<256h',*pcm))
(root/'tone.wav').write_bytes(chunk(b'RIFF',wave))
# 48000 in IEEE extended-80 format.
comm=s.pack('>hIh',1,frames,16)+bytes.fromhex('400ebb80000000000000')
aiff=b'AIFF'+chunk(b'COMM',comm,True)+chunk(b'SSND',b'\0'*8+s.pack('>256h',*pcm),True)
(root/'tone.aiff').write_bytes(chunk(b'FORM',aiff,True))
sfz='<control> default_path=./\n<global> ampeg_release=0.01 pitch_keycenter=c4\n<group> lokey=48 hikey=72 lovel=1 hivel=127 loop_mode=loop_sustain loop_start=32 loop_end=223\n<region> sample=tone.wav seq_length=2 seq_position=1 pan=-100\n<region> sample=tone.wav seq_length=2 seq_position=2 pan=100\n'
(root/'layers.sfz').write_text(sfz)
(root/'missing.sfz').write_text('<region> sample=absent.wav')
(root/'bad.sf2').write_bytes(b'RIFF\x00\x01\x00\x00sfbk')
# Tiny SF2 with one preset, one instrument and one sample.
ph=name('Test',20)+s.pack('<HHHIII',0,0,0,0,0,0)+name('EOP',20)+s.pack('<HHHIII',0,0,1,0,0,0)
pb=s.pack('<4H',0,0,1,0);pg=s.pack('<4H',41,0,0,0)
inst=name('Tone',20)+s.pack('<H',0)+name('EOI',20)+s.pack('<H',1)
igen=[(53,0),(54,3),(34,(-12000)&65535),(38,(-6000)&65535)]
ib=s.pack('<4H',0,0,len(igen),0)
ig=b''.join(s.pack('<HH',*g) for g in igen)+b'\0'*4
sh=name('Tone',20)+s.pack('<5IBbHH',0,frames,32,224,48000,60,0,0,1)+name('EOS',20)+b'\0'*26
pdta=b'pdta'+b''.join(chunk(k,v) for k,v in [(b'phdr',ph),(b'pbag',pb),(b'pmod',b'\0'*10),(b'pgen',pg),(b'inst',inst),(b'ibag',ib),(b'imod',b'\0'*10),(b'igen',ig),(b'shdr',sh)])
sf=b'sfbk'+chunk(b'LIST',b'INFO'+chunk(b'ifil',s.pack('<HH',2,1)))+chunk(b'LIST',b'sdta'+chunk(b'smpl',s.pack('<256h',*pcm)+b'\0'*92))+chunk(b'LIST',pdta)
(root/'tone.sf2').write_bytes(chunk(b'RIFF',sf))
# EXS little-endian chunk variant using the documented MIT parser offsets.
def exs(kind,size):
 b=bytearray(84+size);s.pack_into('<I',b,0,kind<<24);s.pack_into('<I',b,4,size);b[16:20]=b'TBOS';return b
head=exs(0,0);head[20:24]=b'Test'
zone=exs(1,104);zone[85]=60;zone[90:92]=bytes([48,72]);s.pack_into('<II',zone,96,0,frames);s.pack_into('<II',zone,104,32,224);zone[117]=1;s.pack_into('<II',zone,172,0xffffffff,0)
sample=exs(3,336);sample[20:28]=b'tone.wav';s.pack_into('<I',sample,88,frames)
(root/'tone.exs').write_bytes(head+zone+sample)
za,zb=bytearray(zone),bytearray(zone)
za[90:92]=bytes([60,60]);zb[90:92]=bytes([61,61]);s.pack_into('<I',zb,176,1)
sa,sb=bytearray(sample),bytearray(sample)
for record,folder in [(sa,'Forsythia'),(sb,'Horsehair')]:
 directory=(('C:/Library/Application Support/Logic/Samples/Bows/'+folder) if folder=='Forsythia' else ('Macintosh HD:Library:Application Support:Logic:Samples:Bows:'+folder)).encode()
 record[164:164+len(directory)]=directory
with zipfile.ZipFile(root/'exs-paths.zip','w',compression=zipfile.ZIP_DEFLATED) as z:
 z.writestr(zipfile.ZipInfo('Mappings/bows.exs'),head+za+zb+sa+sb,compress_type=zipfile.ZIP_DEFLATED)
 for folder in ['Forsythia','Horsehair']:
  z.writestr(zipfile.ZipInfo('Samples/Bows/'+folder+'/tone.wav'),(root/'tone.wav').read_bytes(),compress_type=zipfile.ZIP_DEFLATED)
for method,label in [(zipfile.ZIP_STORED,'stored'),(zipfile.ZIP_DEFLATED,'deflated')]:
 with zipfile.ZipFile(root/(label+'.zip'),'w',compression=method) as z:
  z.writestr(zipfile.ZipInfo('/'), b'', compress_type=zipfile.ZIP_STORED)
  for n in ['tone.wav','layers.sfz','tone.sf2','tone.exs','tone.aiff']:z.writestr(zipfile.ZipInfo('nested/'+n), (root/n).read_bytes(), compress_type=method)
with zipfile.ZipFile(root/'traversal.zip','w') as z:z.writestr('../escape.sfz',sfz)
(root/'README.txt').write_text('Original synthetic fixtures generated by tools/soundbanks/make_fixtures.py; same MIT license as ChooChooTracker. The separate fluid-gun.ogg and tone SF3 fixtures contain an unmodified MIT-licensed FluidR3Mono sample. See FluidR3Mono-LICENSE.txt and SF3-SOURCE.txt.\n')

# Same fixture layout with an unmodified compressed sample from FluidR3Mono.
ogg=(root/'fluid-gun.ogg').read_bytes()
for exclusive in (False,True):
 sf3sh=name('Fluid gun excerpt',20)+s.pack('<5IBbHH',0,len(ogg)-(not exclusive),0,0,11025,60,0,0,17)+name('EOS',20)+b'\0'*26
 sf3ig=s.pack('<4H',53,0,54,0)+b'\0'*4
 sf3ib=s.pack('<4H',0,0,2,0)
 sf3pdta=b'pdta'+b''.join(chunk(k,v) for k,v in [(b'phdr',ph),(b'pbag',pb),(b'pmod',b'\0'*10),(b'pgen',pg),(b'inst',inst),(b'ibag',sf3ib),(b'imod',b'\0'*10),(b'igen',sf3ig),(b'shdr',sf3sh)])
 sf3=b'sfbk'+chunk(b'LIST',b'INFO'+chunk(b'ifil',s.pack('<HH',3,1)))+chunk(b'LIST',b'sdta'+chunk(b'smpl',ogg))+chunk(b'LIST',sf3pdta)
 (root/('tone-exclusive.sf3' if exclusive else 'tone.sf3')).write_bytes(chunk(b'RIFF',sf3))
